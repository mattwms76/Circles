import { readFileSync, writeFileSync } from 'node:fs';
const tokens = JSON.parse(readFileSync('src/design-tokens.json', 'utf8'));
const metrics = JSON.parse(readFileSync('src/design-metrics.json', 'utf8'));
const icons = JSON.parse(readFileSync('src/icon-paths.json', 'utf8'));
const block =
  '/* generated-tokens:start */\n' +
  Object.entries(tokens)
    .map(
      ([mode, colors]) =>
        `${mode === 'light' ? ':root' : ":root[data-theme='dark']"} {\n${Object.entries(colors)
          .map(([key, value]) => `  --${key}: ${value};`)
          .join('\n')}\n}`,
    )
    .join('\n') +
  '\n:root {\n' +
  Object.entries(metrics.spacing)
    .map(([key, value]) => `  --space-${key}: ${value}px;`)
    .join('\n') +
  '\n' +
  Object.entries(metrics.radii)
    .map(([key, value]) => `  --radius-${key}: ${value}px;`)
    .join('\n') +
  '\n' +
  Object.entries(metrics.typography)
    .flatMap(([key, value]) => [
      `  --type-${key}-size: ${value.fontSize}px;`,
      `  --type-${key}-line: ${value.lineHeight}px;`,
    ])
    .join('\n') +
  '\n}\n/* generated-tokens:end */';
const path = 'preview-design.css',
  source = readFileSync(path, 'utf8').replace(/\r\n/g, '\n');
const next = source.includes('/* generated-tokens:start */')
  ? source.replace(/\/\* generated-tokens:start \*\/[\s\S]*?\/\* generated-tokens:end \*\//, block)
  : source + '\n' + block + '\n';
if (process.argv.includes('--check')) {
  if (source !== next) {
    console.error('Preview tokens differ from native. Run pnpm tokens:sync.');
    process.exitCode = 1;
  }
} else writeFileSync(path, next);
const iconPath = 'preview-icons.js';
const iconSource = `/* Generated by scripts/design-tokens.mjs; edit src/icon-paths.json. */\nwindow.CirclesIconPaths = ${JSON.stringify(icons)};\nwindow.circlesIcon = function(name) { const paths = window.CirclesIconPaths[name] || window.CirclesIconPaths.more; return '<svg aria-hidden="true" focusable="false" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="' + (name === 'more' ? 3.5 : 1.75) + '" stroke-linecap="round" stroke-linejoin="round">' + paths.map(d => '<path d="' + d + '"/>').join('') + '</svg>'; };\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(iconPath, 'utf8').replace(/\r\n/g, '\n') !== iconSource) {
    console.error('Preview icons differ from native. Run pnpm tokens:sync.');
    process.exitCode = 1;
  }
} else writeFileSync(iconPath, iconSource);
