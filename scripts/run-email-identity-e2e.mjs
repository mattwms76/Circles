#!/usr/bin/env node
/**
 * Opt-in, disposable PG17 end-to-end drill for EmailIdentityStore allocation.
 * It imports the real TypeScript store and transaction-aware user helper through
 * tsx; it never reads application/provider credentials or contacts a network.
 *
 * Run from the repository root with:
 * CIRCLES_EMAIL_AUTH_LOCAL_PG17=1 POSTGRES17_BIN=/usr/lib/postgresql/17/bin \
 *   node --import tsx scripts/run-email-identity-e2e.mjs
 */
import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { createServer } from "node:net";
import { tmpdir } from "node:os";
import { join } from "node:path";
import pg from "pg";

if (process.env.CIRCLES_EMAIL_AUTH_LOCAL_PG17 !== "1") {
  console.log(
    "SKIP: set CIRCLES_EMAIL_AUTH_LOCAL_PG17=1 for disposable local PostgreSQL 17 email identity E2E drill",
  );
  process.exit(0);
}

const binDirectory = process.env.POSTGRES17_BIN ?? "/usr/lib/postgresql/17/bin";
const initdb = join(binDirectory, "initdb");
const pgCtl = join(binDirectory, "pg_ctl");
const migrationPath = "operations/migrations/0014_circles_email_identity.sql";

function run(command, argumentsList) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, argumentsList, {
      stdio: ["ignore", "pipe", "pipe"],
    });
    let output = "";
    child.stdout.on("data", (chunk) => {
      output += String(chunk);
    });
    child.stderr.on("data", (chunk) => {
      output += String(chunk);
    });
    child.once("error", reject);
    child.once("exit", (code) => {
      if (code === 0) resolve(output);
      else {
        reject(
          new Error(
            `${command} exited ${code ?? "unknown"}: ${output.slice(-500)}`,
          ),
        );
      }
    });
  });
}

async function unusedPort() {
  const server = createServer();
  await new Promise((resolve, reject) => {
    server.once("error", reject);
    server.listen(0, "127.0.0.1", resolve);
  });
  const address = server.address();
  assert(address && typeof address === "object");
  const { port } = address;
  await new Promise((resolve, reject) =>
    server.close((error) => (error ? reject(error) : resolve())),
  );
  return port;
}

function localClient(port) {
  return new pg.Client({
    host: "127.0.0.1",
    port,
    user: "postgres",
    database: "postgres",
  });
}

function identity(subject, email, name = "Fixture member") {
  return { subject, email, name };
}

async function countRows(admin, statement, values = []) {
  const result = await admin.query(statement, values);
  return Number(result.rows[0]?.count ?? 0);
}

const directory = await mkdtemp(
  join(tmpdir(), "circles-email-identity-e2e-pg17-"),
);
const dataDirectory = join(directory, "data");
const port = await unusedPort();
let admin;
let runtimePool;
try {
  await run(initdb, [
    "-D",
    dataDirectory,
    "-A",
    "trust",
    "-U",
    "postgres",
    "--no-locale",
    "-E",
    "UTF8",
  ]);
  await run(pgCtl, [
    "-D",
    dataDirectory,
    "-o",
    `-h 127.0.0.1 -p ${port} -k ${directory}`,
    "-w",
    "start",
  ]);
  admin = localClient(port);
  await admin.connect();

  await admin.query(`
    CREATE ROLE anon NOLOGIN;
    CREATE ROLE authenticated NOLOGIN;
    CREATE ROLE service_role NOLOGIN;
    CREATE ROLE circles_app_runtime NOLOGIN NOINHERIT NOBYPASSRLS;

    CREATE SCHEMA circles_app AUTHORIZATION postgres;
    CREATE TYPE circles_app.user_role AS ENUM ('user', 'admin');
    CREATE TABLE circles_app.users (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      "openId" varchar(64) NOT NULL UNIQUE,
      name text,
      email varchar(320),
      "loginMethod" varchar(64),
      role circles_app.user_role NOT NULL DEFAULT 'user',
      "createdAt" timestamptz NOT NULL DEFAULT pg_catalog.clock_timestamp(),
      "updatedAt" timestamptz NOT NULL DEFAULT pg_catalog.clock_timestamp(),
      "lastSignedIn" timestamptz NOT NULL DEFAULT pg_catalog.clock_timestamp()
    );
    ALTER TABLE circles_app.users ENABLE ROW LEVEL SECURITY;
    ALTER TABLE circles_app.users FORCE ROW LEVEL SECURITY;
    REVOKE ALL ON SCHEMA circles_app FROM PUBLIC, anon, authenticated, service_role, circles_app_runtime;
    GRANT USAGE ON SCHEMA circles_app TO circles_app_runtime;
    REVOKE ALL ON TABLE circles_app.users FROM PUBLIC, anon, authenticated, service_role, circles_app_runtime;
    GRANT SELECT, INSERT, UPDATE ON TABLE circles_app.users TO circles_app_runtime;
    GRANT USAGE, SELECT ON SEQUENCE circles_app.users_id_seq TO circles_app_runtime;
    CREATE POLICY circles_app_users_runtime_all ON circles_app.users
      FOR ALL TO circles_app_runtime USING (true) WITH CHECK (true);

    CREATE SCHEMA circles_admin AUTHORIZATION postgres;
    CREATE TABLE circles_admin.feature_state (
      singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
      registrations_open boolean NOT NULL,
      available boolean NOT NULL
    );
    INSERT INTO circles_admin.feature_state (singleton, registrations_open, available)
      VALUES (true, true, true);
    CREATE FUNCTION circles_admin.read_mobile_feature_settings()
      RETURNS jsonb
      LANGUAGE plpgsql
      SECURITY DEFINER
      SET search_path = pg_catalog, circles_admin
      AS $$
      DECLARE settings jsonb;
      BEGIN
        SELECT CASE WHEN feature_state.available THEN jsonb_build_object(
          'registrationsOpen', feature_state.registrations_open,
          'circleCreationEnabled', true,
          'liveStreamingEnabled', true,
          'maintenanceMode', false,
          'maxUploadMb', 20
        ) ELSE NULL END
          INTO settings
          FROM circles_admin.feature_state AS feature_state
          WHERE feature_state.singleton
          FOR SHARE;
        RETURN settings;
      END;
      $$;
    REVOKE ALL ON SCHEMA circles_admin FROM PUBLIC, anon, authenticated, service_role, circles_app_runtime;
    GRANT USAGE ON SCHEMA circles_admin TO circles_app_runtime;
    REVOKE ALL ON FUNCTION circles_admin.read_mobile_feature_settings() FROM PUBLIC;
    GRANT EXECUTE ON FUNCTION circles_admin.read_mobile_feature_settings() TO circles_app_runtime;

    INSERT INTO circles_app.users (id, "openId", name, email, "loginMethod", role)
      VALUES
        (100, 'fixture-owner', 'Owner', 'owner@example.test', 'manus', 'admin'),
        (101, 'fixture-actor-a', 'Actor A', 'actor-a@example.test', 'manus', 'user'),
        (102, 'fixture-actor-b', 'Actor B', 'actor-b@example.test', 'manus', 'user');
  `);
  await admin.query(await readFile(migrationPath, "utf8"));

  // Import only after the fixture selects a synthetic owner and the initially
  // inactive feature-reader mode. ENV is intentionally read at module import.
  process.env.OWNER_OPEN_ID = "fixture-owner";
  delete process.env.CIRCLES_PLATFORM_SETTINGS_ENABLED;
  const [{ drizzle }, { RuntimeRolePool }, identityModule, dbModule] =
    await Promise.all([
      import("drizzle-orm/node-postgres"),
      import("../server/runtime-role-pool.ts"),
      import("../server/_core/email-identity.ts"),
      import("../server/db.ts"),
    ]);
  const { EmailIdentityLinkRequiredError, EmailIdentityStore } = identityModule;
  const { lockUserEmailAllocation, upsertUserInTransaction } = dbModule;

  runtimePool = new RuntimeRolePool({
    host: "127.0.0.1",
    port,
    user: "postgres",
    database: "postgres",
    max: 8,
  });
  const database = drizzle(runtimePool);
  const store = new EmailIdentityStore({
    getDatabase: async () => database,
  });

  assert.equal(await store.isReady(), true);

  // Inactive is the default mode: a real source allocation succeeds through the
  // helper and retains the schema default role rather than promoting an actor.
  const inactive = await store.resolveForSignIn(
    identity("11111111-1111-4111-8111-111111111111", "inactive@example.test"),
  );
  const inactiveSource = await admin.query(
    `SELECT role::text AS role, "loginMethod" AS "loginMethod"
       FROM circles_app.users WHERE id = $1`,
    [inactive.userId],
  );
  assert.deepEqual(inactiveSource.rows, [
    { role: "user", loginMethod: "email" },
  ]);

  // The active reader has no cache/fallback: unavailable settings reject the
  // first source INSERT. Existing sign-in still updates only lastSignedIn and
  // never asks the unavailable reader.
  process.env.CIRCLES_PLATFORM_SETTINGS_ENABLED = "true";
  await admin.query(
    "UPDATE circles_admin.feature_state SET available = false WHERE singleton",
  );
  await assert.rejects(
    () =>
      database.transaction((transaction) =>
        upsertUserInTransaction(transaction, {
          openId: "unavailable-new-source",
          email: "unavailable@example.test",
          loginMethod: "email",
        }),
      ),
    (error) => error?.code === "SERVICE_UNAVAILABLE",
  );
  assert.equal(
    await countRows(
      admin,
      `SELECT count(*) FROM circles_app.users
       WHERE "openId" = 'unavailable-new-source'`,
    ),
    0,
  );
  const beforeExistingSignIn = await admin.query(
    `SELECT "lastSignedIn" AS "lastSignedIn" FROM circles_app.users
     WHERE "openId" = 'fixture-actor-a'`,
  );
  await new Promise((resolve) => setTimeout(resolve, 5));
  await database.transaction((transaction) =>
    upsertUserInTransaction(transaction, {
      openId: "fixture-actor-a",
      lastSignedIn: new Date(),
    }),
  );
  const afterExistingSignIn = await admin.query(
    `SELECT "lastSignedIn" AS "lastSignedIn" FROM circles_app.users
     WHERE "openId" = 'fixture-actor-a'`,
  );
  assert.notEqual(
    String(beforeExistingSignIn.rows[0].lastSignedIn),
    String(afterExistingSignIn.rows[0].lastSignedIn),
  );

  // Active closed rejects first allocations; active open admits the race drill.
  await admin.query(
    "UPDATE circles_admin.feature_state SET available = true, registrations_open = false WHERE singleton",
  );
  await assert.rejects(
    () =>
      database.transaction((transaction) =>
        upsertUserInTransaction(transaction, {
          openId: "closed-new-source",
          email: "closed@example.test",
          loginMethod: "email",
        }),
      ),
    (error) => error?.code === "FORBIDDEN",
  );
  await admin.query(
    "UPDATE circles_admin.feature_state SET registrations_open = true WHERE singleton",
  );

  // Two distinct verified UUIDs racing on one email share the normalized email
  // lock: exactly one source user and immutable map commit; the other rolls back
  // as LINK_REQUIRED before an extra source allocation.
  const sharedEmail = "race@example.test";
  const firstRaceIdentity = identity(
    "22222222-2222-4222-8222-222222222222",
    sharedEmail,
    "Race one",
  );
  const secondRaceIdentity = identity(
    "33333333-3333-4333-8333-333333333333",
    sharedEmail,
    "Race two",
  );
  const raceResults = await Promise.allSettled([
    store.resolveForSignIn(firstRaceIdentity),
    store.resolveForSignIn(secondRaceIdentity),
  ]);
  const raceSuccesses = raceResults.filter(
    (result) => result.status === "fulfilled",
  );
  const raceFailures = raceResults.filter(
    (result) => result.status === "rejected",
  );
  assert.equal(raceSuccesses.length, 1);
  assert.equal(raceFailures.length, 1);
  assert(raceFailures[0].reason instanceof EmailIdentityLinkRequiredError);
  const raceWinner = raceSuccesses[0].value;
  assert.equal(
    await countRows(
      admin,
      `SELECT count(*) FROM circles_app.users
       WHERE "openId" IN ($1, $2)`,
      [
        `supabase:${firstRaceIdentity.subject}`,
        `supabase:${secondRaceIdentity.subject}`,
      ],
    ),
    1,
  );
  assert.equal(
    await countRows(
      admin,
      `SELECT count(*) FROM circles_identity.provider_links
       WHERE provider_subject IN ($1::uuid, $2::uuid)`,
      [firstRaceIdentity.subject, secondRaceIdentity.subject],
    ),
    1,
  );
  const repeated = await store.resolveForSignIn(
    raceWinner.openId.endsWith(firstRaceIdentity.subject)
      ? firstRaceIdentity
      : secondRaceIdentity,
  );
  assert.equal(repeated.userId, raceWinner.userId);

  // A legacy source allocation that already holds the exact shared email lock
  // serializes the real store. The later provider source attempt becomes a
  // LINK_REQUIRED rollback: one legacy row, no provider source row or map.
  const legacyEmail = "legacy-race@example.test";
  let releaseLegacy;
  const legacyLocked = new Promise((resolve) => {
    releaseLegacy = resolve;
  });
  let notifyLegacyLock;
  const legacyLockHeld = new Promise((resolve) => {
    notifyLegacyLock = resolve;
  });
  const legacyAllocation = database.transaction(async (transaction) => {
    await lockUserEmailAllocation(transaction, legacyEmail);
    notifyLegacyLock();
    await legacyLocked;
    await upsertUserInTransaction(transaction, {
      openId: "legacy:race-source",
      email: legacyEmail,
      loginMethod: "manus",
      name: "Legacy source",
    });
  });
  await legacyLockHeld;
  const collidingProvider = store.resolveForSignIn(
    identity("44444444-4444-4444-8444-444444444444", legacyEmail),
  );
  releaseLegacy();
  await legacyAllocation;
  await assert.rejects(
    () => collidingProvider,
    (error) => error instanceof EmailIdentityLinkRequiredError,
  );
  assert.equal(
    await countRows(
      admin,
      `SELECT count(*) FROM circles_app.users
       WHERE lower(email) = lower($1)`,
      [legacyEmail],
    ),
    1,
  );
  assert.equal(
    await countRows(
      admin,
      `SELECT count(*) FROM circles_identity.provider_links
       WHERE provider_subject = '44444444-4444-4444-8444-444444444444'::uuid`,
    ),
    0,
  );

  // Actor connect has no source-role promotion. Subject and actor-user unique
  // conflicts leave the existing immutable maps and both actor roles unchanged.
  const firstActorSubject = "55555555-5555-4555-8555-555555555555";
  const secondActorSubject = "66666666-6666-4666-8666-666666666666";
  const actorA = await store.linkToExistingUser(
    identity(firstActorSubject, "actor-connect@example.test"),
    101,
  );
  assert.equal(actorA.userId, 101);
  await assert.rejects(
    () =>
      store.linkToExistingUser(
        identity(firstActorSubject, "actor-subject-conflict@example.test"),
        102,
      ),
    (error) => error instanceof EmailIdentityLinkRequiredError,
  );
  await assert.rejects(
    () =>
      store.linkToExistingUser(
        identity(secondActorSubject, "actor-user-conflict@example.test"),
        101,
      ),
    (error) => error instanceof EmailIdentityLinkRequiredError,
  );
  const actorMaps = await admin.query(`
    SELECT provider_subject::text AS subject, user_id AS "userId"
    FROM circles_identity.provider_links
    WHERE user_id IN (101, 102)
    ORDER BY user_id
  `);
  assert.deepEqual(actorMaps.rows, [
    { subject: firstActorSubject, userId: 101 },
  ]);
  const actorRoles = await admin.query(`
    SELECT id, role::text AS role, "loginMethod" AS "loginMethod"
    FROM circles_app.users
    WHERE id IN (101, 102)
    ORDER BY id
  `);
  assert.deepEqual(actorRoles.rows, [
    { id: 101, role: "user", loginMethod: "manus" },
    { id: 102, role: "user", loginMethod: "manus" },
  ]);

  // The real runtime role retains only the migration's private map lease.
  const runtimeClient = await runtimePool.connect();
  try {
    await assert.rejects(
      () =>
        runtimeClient.query(
          "UPDATE circles_identity.provider_links SET user_id = 102 WHERE user_id = 101",
        ),
      (error) => error?.code === "42501",
    );
    await assert.rejects(
      () =>
        runtimeClient.query(
          "DELETE FROM circles_identity.provider_links WHERE user_id = 101",
        ),
      (error) => error?.code === "42501",
    );
  } finally {
    runtimeClient.release();
  }

  console.log(
    "PASS: PG17 real Drizzle EmailIdentityStore/upsert helper race, registration-gate, immutable-map, role, and restricted-runtime drill",
  );
} finally {
  if (runtimePool) await runtimePool.end().catch(() => undefined);
  if (admin) await admin.end().catch(() => undefined);
  await run(pgCtl, [
    "-D",
    dataDirectory,
    "-m",
    "immediate",
    "-w",
    "stop",
  ]).catch(() => undefined);
  await rm(directory, { recursive: true, force: true });
}
