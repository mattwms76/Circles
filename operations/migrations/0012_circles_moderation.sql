-- Moderator Report Workspace v1. Apply only through the reviewed private PostgreSQL migration process.
-- This migration stores aggregate report evidence and final reviewer actions, never reporter IDs or post bodies/media.
BEGIN;

SELECT pg_catalog.pg_advisory_xact_lock(
  pg_catalog.hashtextextended('circles_app.moderation_workspace_v1'::text, 0)
);

DO $moderation_workspace_prerequisites$
BEGIN
  IF pg_catalog.to_regclass('circles_app.circles') IS NULL
     OR pg_catalog.to_regclass('circles_app.posts') IS NULL
     OR pg_catalog.to_regclass('circles_app.reports') IS NULL
     OR pg_catalog.to_regclass('circles_app.users') IS NULL THEN
    RAISE EXCEPTION 'circles_app circles, posts, reports, and users are required before 0012_circles_moderation';
  END IF;
END;
$moderation_workspace_prerequisites$;

-- Report writes already serialize through their circle lock. This protects DDL and the deterministic
-- legacy snapshot while retaining the existing one-report-per-reporter legacy table unchanged.
LOCK TABLE circles_app.circles, circles_app.posts, circles_app.reports, circles_app.users
  IN SHARE ROW EXCLUSIVE MODE;

CREATE TABLE IF NOT EXISTS circles_app."moderationCases" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "circleId" integer NOT NULL REFERENCES circles_app.circles(id) ON DELETE CASCADE,
  "postId" integer REFERENCES circles_app.posts(id) ON DELETE SET NULL,
  "sourcePostId" integer NOT NULL,
  "subjectUserId" integer REFERENCES circles_app.users(id) ON DELETE SET NULL,
  status varchar(16) NOT NULL DEFAULT 'open',
  "reportCount" integer NOT NULL,
  reasons jsonb NOT NULL DEFAULT '[]'::jsonb,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "lastReportedAt" timestamptz NOT NULL DEFAULT now(),
  "resolvedAt" timestamptz,
  CONSTRAINT moderation_cases_circle_source_post_unique UNIQUE ("circleId", "sourcePostId"),
  CONSTRAINT moderation_cases_source_post_positive_check CHECK ("sourcePostId" > 0),
  CONSTRAINT moderation_cases_report_count_positive_check CHECK ("reportCount" > 0),
  CONSTRAINT moderation_cases_status_check CHECK (status IN ('open', 'kept', 'removed')),
  CONSTRAINT moderation_cases_reasons_array_check
    CHECK (pg_catalog.jsonb_typeof(reasons) = 'array' AND pg_catalog.jsonb_array_length(reasons) <= 20)
);

CREATE TABLE IF NOT EXISTS circles_app."moderationActions" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "caseId" integer NOT NULL REFERENCES circles_app."moderationCases"(id) ON DELETE CASCADE,
  "reviewerId" integer REFERENCES circles_app.users(id) ON DELETE SET NULL,
  decision varchar(16) NOT NULL,
  note varchar(500) NOT NULL,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT moderation_actions_case_unique UNIQUE ("caseId"),
  CONSTRAINT moderation_actions_decision_check CHECK (decision IN ('keep', 'remove'))
);

CREATE INDEX IF NOT EXISTS moderation_cases_circle_status_id_idx
  ON circles_app."moderationCases" ("circleId", status, id DESC);
CREATE INDEX IF NOT EXISTS moderation_cases_post_idx
  ON circles_app."moderationCases" ("postId");
CREATE INDEX IF NOT EXISTS moderation_actions_case_id_desc_idx
  ON circles_app."moderationActions" ("caseId", id DESC);
CREATE INDEX IF NOT EXISTS moderation_actions_reviewer_idx
  ON circles_app."moderationActions" ("reviewerId");

ALTER TABLE circles_app."moderationCases" OWNER TO postgres;
ALTER TABLE circles_app."moderationActions" OWNER TO postgres;
ALTER SEQUENCE circles_app."moderationCases_id_seq" OWNER TO postgres;
ALTER SEQUENCE circles_app."moderationActions_id_seq" OWNER TO postgres;

REVOKE ALL ON TABLE circles_app."moderationCases", circles_app."moderationActions"
  FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON SEQUENCE circles_app."moderationCases_id_seq", circles_app."moderationActions_id_seq"
  FROM PUBLIC, anon, authenticated, service_role;

GRANT SELECT, INSERT, UPDATE, DELETE
  ON TABLE circles_app."moderationCases"
  TO circles_app_runtime;
REVOKE UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER ON TABLE circles_app."moderationActions" FROM circles_app_runtime;
GRANT SELECT, INSERT ON TABLE circles_app."moderationActions" TO circles_app_runtime;
GRANT USAGE, SELECT ON SEQUENCE circles_app."moderationCases_id_seq", circles_app."moderationActions_id_seq"
  TO circles_app_runtime;

ALTER TABLE circles_app."moderationCases" ENABLE ROW LEVEL SECURITY;
ALTER TABLE circles_app."moderationCases" FORCE ROW LEVEL SECURITY;
ALTER TABLE circles_app."moderationActions" ENABLE ROW LEVEL SECURITY;
ALTER TABLE circles_app."moderationActions" FORCE ROW LEVEL SECURITY;

CREATE POLICY runtime_moderation_cases_policy
  ON circles_app."moderationCases"
  FOR ALL TO circles_app_runtime
  USING (true) WITH CHECK (true);
CREATE POLICY runtime_moderation_actions_policy
  ON circles_app."moderationActions"
  FOR ALL TO circles_app_runtime
  USING (true) WITH CHECK (true);

-- Map only reports for posts that are presently circle-scoped. The aggregate excludes reporter IDs,
-- and the stable post ID is the case key. Re-running this section converges counts/reasons without
-- reopening a final case or changing its action/note/status.
WITH eligible_reports AS (
  SELECT
    p."circleId",
    p.id AS "sourcePostId",
    p."authorId" AS "subjectUserId",
    CASE
      WHEN pg_catalog.char_length(pg_catalog.btrim(r.reason)) BETWEEN 1 AND 500
        THEN pg_catalog.btrim(r.reason)
      ELSE 'Unspecified report'
    END AS reason,
    r."createdAt",
    r."updatedAt"
  FROM circles_app.reports AS r
  INNER JOIN circles_app.posts AS p ON p.id = r."postId"
  WHERE p."circleId" IS NOT NULL
),
case_totals AS (
  SELECT
    "circleId",
    "sourcePostId",
    max("subjectUserId") AS "subjectUserId",
    count(*)::integer AS "reportCount",
    min("createdAt") AS "createdAt",
    max("updatedAt") AS "lastReportedAt"
  FROM eligible_reports
  GROUP BY "circleId", "sourcePostId"
),
reason_totals AS (
  SELECT "circleId", "sourcePostId", reason, count(*)::integer AS count
  FROM eligible_reports
  GROUP BY "circleId", "sourcePostId", reason
),
ranked_reasons AS (
  SELECT
    "circleId",
    "sourcePostId",
    reason,
    count,
    row_number() OVER (
      PARTITION BY "circleId", "sourcePostId"
      ORDER BY count DESC, reason ASC
    ) AS position
  FROM reason_totals
),
case_reasons AS (
  SELECT
    "circleId",
    "sourcePostId",
    pg_catalog.jsonb_agg(
      pg_catalog.jsonb_build_object('reason', reason, 'count', count)
      ORDER BY count DESC, reason ASC
    ) FILTER (WHERE position <= 20) AS reasons
  FROM ranked_reasons
  GROUP BY "circleId", "sourcePostId"
)
INSERT INTO circles_app."moderationCases" (
  "circleId",
  "postId",
  "sourcePostId",
  "subjectUserId",
  status,
  "reportCount",
  reasons,
  "createdAt",
  "lastReportedAt"
)
SELECT
  totals."circleId",
  totals."sourcePostId",
  totals."sourcePostId",
  totals."subjectUserId",
  'open',
  totals."reportCount",
  reasons.reasons,
  totals."createdAt",
  totals."lastReportedAt"
FROM case_totals AS totals
INNER JOIN case_reasons AS reasons
  ON reasons."circleId" = totals."circleId"
  AND reasons."sourcePostId" = totals."sourcePostId"
ON CONFLICT ("circleId", "sourcePostId") DO UPDATE
SET
  "postId" = EXCLUDED."postId",
  "subjectUserId" = EXCLUDED."subjectUserId",
  "reportCount" = EXCLUDED."reportCount",
  reasons = EXCLUDED.reasons,
  "lastReportedAt" = EXCLUDED."lastReportedAt";

COMMIT;
