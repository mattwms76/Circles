-- Durable recipient-private in-app Activity Inbox. Apply only through the reviewed private migration process.
BEGIN;

-- Serialize source-table shape/FK creation with social writes while this additive migration commits.
LOCK TABLE circles_app.users, circles_app.circles, circles_app.posts, circles_app.comments, circles_app.memberships IN SHARE ROW EXCLUSIVE MODE;

CREATE TABLE circles_app."activityItems" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "recipientId" integer NOT NULL REFERENCES circles_app.users(id) ON DELETE CASCADE,
  "actorId" integer REFERENCES circles_app.users(id) ON DELETE SET NULL,
  kind varchar(32) NOT NULL,
  "sourceId" integer NOT NULL,
  "circleId" integer REFERENCES circles_app.circles(id) ON DELETE SET NULL,
  "postId" integer REFERENCES circles_app.posts(id) ON DELETE SET NULL,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "readAt" timestamptz,
  CONSTRAINT activity_items_kind_check
    CHECK (kind IN ('comment_on_your_post', 'membership_approved')),
  CONSTRAINT activity_items_source_id_positive_check CHECK ("sourceId" > 0),
  -- FK SET NULL preserves deleted-source activity as an unavailable tombstone. Current
  -- source hooks supply targets; only approval's never-a-post invariant survives deletion.
  CONSTRAINT activity_items_target_shape_check
    CHECK (kind <> 'membership_approved' OR "postId" IS NULL),
  CONSTRAINT activity_items_recipient_kind_source_unique
    UNIQUE ("recipientId", kind, "sourceId")
);

CREATE TABLE circles_app."activityPreferences" (
  "recipientId" integer PRIMARY KEY REFERENCES circles_app.users(id) ON DELETE CASCADE,
  "commentsEnabled" boolean NOT NULL DEFAULT true,
  "membershipApprovalsEnabled" boolean NOT NULL DEFAULT true,
  "updatedAt" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE circles_app."activityCirclePreferences" (
  "recipientId" integer NOT NULL REFERENCES circles_app.users(id) ON DELETE CASCADE,
  "circleId" integer NOT NULL REFERENCES circles_app.circles(id) ON DELETE CASCADE,
  muted boolean NOT NULL DEFAULT false,
  "updatedAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT activity_circle_preferences_recipient_circle_pkey
    PRIMARY KEY ("recipientId", "circleId")
);

CREATE INDEX activity_items_recipient_id_desc_idx
  ON circles_app."activityItems" ("recipientId", id DESC);
CREATE INDEX activity_items_recipient_unread_idx
  ON circles_app."activityItems" ("recipientId", id DESC)
  WHERE "readAt" IS NULL;
CREATE INDEX activity_items_actor_idx ON circles_app."activityItems" ("actorId");
CREATE INDEX activity_items_circle_idx ON circles_app."activityItems" ("circleId");
CREATE INDEX activity_items_post_idx ON circles_app."activityItems" ("postId");
CREATE INDEX activity_circle_preferences_circle_idx
  ON circles_app."activityCirclePreferences" ("circleId");

ALTER TABLE circles_app."activityItems" OWNER TO postgres;
ALTER TABLE circles_app."activityPreferences" OWNER TO postgres;
ALTER TABLE circles_app."activityCirclePreferences" OWNER TO postgres;
ALTER SEQUENCE circles_app."activityItems_id_seq" OWNER TO postgres;

REVOKE ALL ON TABLE circles_app."activityItems", circles_app."activityPreferences", circles_app."activityCirclePreferences"
  FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON SEQUENCE circles_app."activityItems_id_seq"
  FROM PUBLIC, anon, authenticated, service_role;

GRANT SELECT, INSERT, UPDATE, DELETE
  ON TABLE circles_app."activityItems", circles_app."activityPreferences", circles_app."activityCirclePreferences"
  TO circles_app_runtime;
GRANT USAGE, SELECT ON SEQUENCE circles_app."activityItems_id_seq" TO circles_app_runtime;

ALTER TABLE circles_app."activityItems" ENABLE ROW LEVEL SECURITY;
ALTER TABLE circles_app."activityItems" FORCE ROW LEVEL SECURITY;
ALTER TABLE circles_app."activityPreferences" ENABLE ROW LEVEL SECURITY;
ALTER TABLE circles_app."activityPreferences" FORCE ROW LEVEL SECURITY;
ALTER TABLE circles_app."activityCirclePreferences" ENABLE ROW LEVEL SECURITY;
ALTER TABLE circles_app."activityCirclePreferences" FORCE ROW LEVEL SECURITY;

CREATE POLICY runtime_activity_items_policy
  ON circles_app."activityItems"
  FOR ALL TO circles_app_runtime
  USING (true) WITH CHECK (true);
CREATE POLICY runtime_activity_preferences_policy
  ON circles_app."activityPreferences"
  FOR ALL TO circles_app_runtime
  USING (true) WITH CHECK (true);
CREATE POLICY runtime_activity_circle_preferences_policy
  ON circles_app."activityCirclePreferences"
  FOR ALL TO circles_app_runtime
  USING (true) WITH CHECK (true);

COMMIT;
