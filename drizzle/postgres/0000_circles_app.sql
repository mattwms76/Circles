-- Offline-only private Circles PostgreSQL baseline.
-- Apply only after the parent verifies that circles_app and circles_app_runtime do not already exist.
-- This migration intentionally does not touch public, private, auth, storage, or archival MySQL migrations.

CREATE ROLE circles_app_runtime NOLOGIN NOINHERIT NOBYPASSRLS;
CREATE SCHEMA circles_app AUTHORIZATION postgres;
GRANT circles_app_runtime TO postgres;

REVOKE ALL ON SCHEMA circles_app FROM PUBLIC, anon, authenticated, service_role;
GRANT USAGE ON SCHEMA circles_app TO circles_app_runtime;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA circles_app REVOKE ALL ON TABLES FROM PUBLIC, anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA circles_app REVOKE ALL ON SEQUENCES FROM PUBLIC, anon, authenticated, service_role;

CREATE TYPE circles_app.user_role AS ENUM ('user', 'admin');
CREATE TYPE circles_app.circle_privacy AS ENUM ('public', 'private');
CREATE TYPE circles_app.membership_role AS ENUM ('owner', 'moderator', 'member', 'pending');
CREATE TYPE circles_app.media_type AS ENUM ('text', 'photo', 'video');
CREATE TYPE circles_app.reaction_type AS ENUM ('like');
CREATE TYPE circles_app.conversation_kind AS ENUM ('direct', 'circle');
CREATE TYPE circles_app.stream_status AS ENUM ('live', 'ended');
CREATE TYPE circles_app.live_signal_kind AS ENUM ('join', 'offer', 'answer', 'ice', 'leave');

CREATE TABLE circles_app.users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "openId" varchar(64) NOT NULL UNIQUE,
  name text,
  email varchar(320),
  "loginMethod" varchar(64),
  role circles_app.user_role NOT NULL DEFAULT 'user',
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now(),
  "lastSignedIn" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE circles_app.profiles (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId" integer NOT NULL REFERENCES circles_app.users(id) ON DELETE CASCADE,
  name varchar(120) NOT NULL,
  handle varchar(48) NOT NULL,
  bio text NOT NULL,
  avatar varchar(2048) NOT NULL,
  cover varchar(2048),
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT profiles_user_id_unique UNIQUE ("userId")
);

CREATE TABLE circles_app.circles (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ownerId" integer NOT NULL REFERENCES circles_app.users(id) ON DELETE RESTRICT,
  name varchar(140) NOT NULL,
  description text NOT NULL,
  category varchar(80) NOT NULL,
  privacy circles_app.circle_privacy NOT NULL DEFAULT 'public',
  image varchar(2048) NOT NULL DEFAULT '',
  color varchar(32) NOT NULL DEFAULT '#ED604A',
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE circles_app.memberships (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "circleId" integer NOT NULL REFERENCES circles_app.circles(id) ON DELETE CASCADE,
  "userId" integer NOT NULL REFERENCES circles_app.users(id) ON DELETE CASCADE,
  role circles_app.membership_role NOT NULL DEFAULT 'member',
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT memberships_circle_user_unique UNIQUE ("circleId", "userId")
);

CREATE TABLE circles_app.posts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "authorId" integer NOT NULL REFERENCES circles_app.users(id) ON DELETE CASCADE,
  "circleId" integer REFERENCES circles_app.circles(id) ON DELETE CASCADE,
  text text NOT NULL,
  media varchar(2048),
  "mediaType" circles_app.media_type NOT NULL DEFAULT 'text',
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE circles_app.reactions (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "postId" integer NOT NULL REFERENCES circles_app.posts(id) ON DELETE CASCADE,
  "userId" integer NOT NULL REFERENCES circles_app.users(id) ON DELETE CASCADE,
  type circles_app.reaction_type NOT NULL DEFAULT 'like',
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT reactions_post_user_unique UNIQUE ("postId", "userId")
);

CREATE TABLE circles_app.bookmarks (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "postId" integer NOT NULL REFERENCES circles_app.posts(id) ON DELETE CASCADE,
  "userId" integer NOT NULL REFERENCES circles_app.users(id) ON DELETE CASCADE,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT bookmarks_post_user_unique UNIQUE ("postId", "userId")
);

CREATE TABLE circles_app.comments (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "postId" integer NOT NULL REFERENCES circles_app.posts(id) ON DELETE CASCADE,
  "authorId" integer NOT NULL REFERENCES circles_app.users(id) ON DELETE CASCADE,
  text text NOT NULL,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE circles_app.conversations (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind circles_app.conversation_kind NOT NULL,
  "directKey" varchar(64),
  "circleId" integer REFERENCES circles_app.circles(id) ON DELETE CASCADE,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT conversations_direct_key_unique UNIQUE ("directKey"),
  CONSTRAINT conversations_circle_id_unique UNIQUE ("circleId")
);

CREATE TABLE circles_app."conversationParticipants" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "conversationId" integer NOT NULL REFERENCES circles_app.conversations(id) ON DELETE CASCADE,
  "userId" integer NOT NULL REFERENCES circles_app.users(id) ON DELETE CASCADE,
  "lastReadMessageId" integer NOT NULL DEFAULT 0,
  "lastReadAt" timestamptz,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT conversation_participants_conversation_user_unique UNIQUE ("conversationId", "userId")
);

CREATE TABLE circles_app.messages (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "conversationId" integer NOT NULL REFERENCES circles_app.conversations(id) ON DELETE CASCADE,
  "authorId" integer NOT NULL REFERENCES circles_app.users(id) ON DELETE CASCADE,
  text text NOT NULL,
  media varchar(2048),
  "createdAt" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE circles_app.follows (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "followerId" integer NOT NULL REFERENCES circles_app.users(id) ON DELETE CASCADE,
  "followingId" integer NOT NULL REFERENCES circles_app.users(id) ON DELETE CASCADE,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT follows_follower_following_unique UNIQUE ("followerId", "followingId")
);

CREATE TABLE circles_app.reports (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "postId" integer NOT NULL REFERENCES circles_app.posts(id) ON DELETE CASCADE,
  "reporterId" integer NOT NULL REFERENCES circles_app.users(id) ON DELETE CASCADE,
  reason varchar(500) NOT NULL,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT reports_post_reporter_unique UNIQUE ("postId", "reporterId")
);

CREATE TABLE circles_app."socialUploads" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId" integer NOT NULL REFERENCES circles_app.users(id) ON DELETE CASCADE,
  "storageKey" varchar(1024) NOT NULL,
  url varchar(2048) NOT NULL,
  "mimeType" varchar(128) NOT NULL,
  bytes integer NOT NULL,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT social_uploads_storage_key_unique UNIQUE ("storageKey")
);

CREATE TABLE circles_app."socialSeedMarkers" (
  key varchar(100) PRIMARY KEY,
  "completedAt" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE circles_app."_dataMigrations" (
  key text PRIMARY KEY,
  "sourceTree" text NOT NULL,
  "completedAt" timestamptz NOT NULL,
  summary jsonb NOT NULL
);

CREATE TABLE circles_app."applicationSessions" (
  "sessionFingerprint" varchar(64) PRIMARY KEY,
  "userOpenId" varchar(64) NOT NULL,
  "appId" varchar(128) NOT NULL,
  "expiresAt" timestamptz NOT NULL,
  "revokedAt" timestamptz,
  "createdAt" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE circles_app.streams (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "hostId" integer NOT NULL,
  title varchar(160) NOT NULL,
  "circleId" integer,
  thumbnail varchar(2048) NOT NULL DEFAULT '',
  status circles_app.stream_status NOT NULL DEFAULT 'live',
  "readyAt" timestamptz,
  "lastHeartbeatAt" timestamptz NOT NULL DEFAULT now(),
  "hostGeneration" integer NOT NULL DEFAULT 1,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "endedAt" timestamptz
);

CREATE TABLE circles_app."activeHostLeases" (
  "hostId" integer PRIMARY KEY,
  "streamId" integer,
  "lastHeartbeatAt" timestamptz
);

CREATE TABLE circles_app."liveViewers" (
  "streamId" integer NOT NULL,
  "userId" integer NOT NULL,
  "joinedAt" timestamptz NOT NULL DEFAULT now(),
  "lastSeenAt" timestamptz NOT NULL DEFAULT now(),
  generation integer NOT NULL DEFAULT 1,
  "leftAt" timestamptz,
  PRIMARY KEY ("streamId", "userId")
);

CREATE TABLE circles_app."liveSignals" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "streamId" integer NOT NULL,
  "fromId" integer NOT NULL,
  "toId" integer,
  kind circles_app.live_signal_kind NOT NULL,
  "fromGeneration" integer NOT NULL DEFAULT 1,
  "toGeneration" integer NOT NULL DEFAULT 1,
  payload text NOT NULL,
  "createdAt" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE circles_app."liveChat" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "streamId" integer NOT NULL,
  "userId" integer NOT NULL,
  "userName" varchar(160) NOT NULL,
  avatar varchar(2048) NOT NULL DEFAULT '',
  text varchar(500) NOT NULL,
  "createdAt" timestamptz NOT NULL DEFAULT now()
);

